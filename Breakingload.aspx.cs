        private bool Submitform()
        {
            try
            {
                if (_cm == null) _cm = new DAL.CM();

                if (Request.QueryString["s"] != null)
                    _cm.sampleId = Convert.ToInt32(Request.QueryString["s"].ToLower());
                if (Request.QueryString["r"] != null)
                    _cm.ReportID = Request.QueryString["r"];

                DataTable dt1 = _cm.Getdataforseriesandreportid_mechanical(_cm);
                if (dt1.Rows.Count > 0)
                {
                    _cm.sampleIDSeries = dt1.Rows[0]["sampleIDSeries"].ToString();
                    _cm.CRFSampleId = Convert.ToInt32(dt1.Rows[0]["CRFSampleId"]);
                }

                List<string> reportParamMapList = new List<string>();
                List<string> resultList = new List<string>();

                // Only BreakingLoad (use new ID 12649)
                reportParamMapList.Add("12649");
                resultList.Add($"{ddlUnit.SelectedValue}|{txtspecified.Text.Trim()}|{txtmeasurement.Text.Trim()}");

                reportParamMapList.Add("12650"); resultList.Add(cableType.Text);
                reportParamMapList.Add("12651"); resultList.Add(cableSize.Text);
                reportParamMapList.Add("12652"); resultList.Add(grade.Text);
                reportParamMapList.Add("12656"); resultList.Add(refSpec.Text);
                reportParamMapList.Add("12657"); resultList.Add(testMethodNo.Text);
                reportParamMapList.Add("12658"); resultList.Add(jobOrderNo.Text);
                reportParamMapList.Add("12659"); resultList.Add(worksheetno.Text);
                reportParamMapList.Add("12654"); resultList.Add(roomno.Text);
                reportParamMapList.Add("12660"); resultList.Add(roomhumidity.Text);
                reportParamMapList.Add("12655"); resultList.Add(roomtemp.Text);
                reportParamMapList.Add("12653"); resultList.Add(Date.Text);
                reportParamMapList.Add("12661"); resultList.Add(equipmentno.Text);

                // Convert to arrays and submit
                string[] reportParamMap = reportParamMapList.ToArray();
                string[] result = resultList.ToArray();
                int modified = _cm.AddTestResultPTQualis(_cm, reportParamMap, result);

                if (modified > 0)
                {
                    _cm.sampleStatusID = 27;
                    _cm.UpdateCRFSampleDetailsStatus(_cm);

                    _cm.StatusID = 27;
                    _cm.UpdateAllocationStatusid_mechanical(_cm);

                    ScriptManager.RegisterStartupScript(this, this.GetType(), "showSuccess",
                        "alert('Data saved successfully!');", true);

                    Response.Redirect($"GenerateTestReportBreakingload.aspx?s={_cm.sampleId}&r={_cm.ReportID}");
                    return true;
                }
                else
                {
                    ScriptManager.RegisterStartupScript(this, this.GetType(), "showError",
                        "alert('Failed to save data.');", true);
                    return false;
                }
            }
            catch (Exception ex)
            {
                ScriptManager.RegisterStartupScript(this, this.GetType(), "showError",
                    $"alert('Error: {ex.Message}');", true);
                return false;
            }
        }
